"""
NBA CBA trade-variation validator for the 2026-27 system.

This module is designed to consume the GENERIC trade dictionaries produced by
trade_variations.py, for example:

    {
        "trade_type": "3_team",
        "teams": ("Team A", "Team B", "Team C"),
        "moves": (
            {
                "from_team": "Team A",
                "to_team": "Team B",
                "players": ("Player 1",),
            },
            ...
        ),
    }

It deliberately does not depend on the specific wanted_players/tradeable_players
input that generated a trade. It validates the completed trade candidate.

Rules implemented are based on the supplied "NBA Trade CBA Rules Reference"
for 2026-27. The workbook is used for player contracts, current salary, team
cap/apron data, trade exceptions when available, and draft assets.

IMPORTANT LIMITATION
--------------------
Some CBA rules require facts that are not present in the supplied workbook,
such as exact signing dates, acquisition dates, Bird-rights veto status,
no-trade clauses, matched-offer-sheet consent, trade bonuses, and exact special
trade-salary treatment. The validator therefore follows this principle:

    Reject a trade when the available data proves a violation.
    Do not invent missing facts merely to reject a candidate.

For missing facts, pass `player_overrides` / `team_overrides`. ValidationResult
also reports `undetermined` checks so that "passes" means "no detected CBA
violation using the available data", not a league-office certification.

Runtime dependency:
    openpyxl

Typical use:

    from datetime import date
    from cba_trade_rules import CBAValidator, SeasonRules

    rules = SeasonRules(
        trade_deadline=None,  # fill from your season-level data when known
        regular_season_start=None,
    )

    validator = CBAValidator.from_xlsx(
        "nba_trade_engine_data.xlsx",
        trade_date=date(2026, 10, 7),
        rules=rules,
    )

    legal_trades = list(validator.iter_legal_trades(all_trade_variations))

For an audit:

    legal, rejected = validator.filter_trades(
        all_trade_variations,
        keep_rejections=True,
        rejection_limit=500,
    )

PLAYER OVERRIDES
----------------
Keys are `(team_name, player_name)`. Recognized fields include:

    signed_date: date | "YYYY-MM-DD"
    acquired_date: date | "YYYY-MM-DD"
    jan15_restricted: bool
    bird_trade_veto: bool
    no_trade_clause: bool
    trade_consent: bool
    matched_rfa_date: date | "YYYY-MM-DD"
    matched_rfa_offer_team: str
    designated_veteran_signed_date: date | "YYYY-MM-DD"
    extension_signed_date: date | "YYYY-MM-DD"
    renegotiated_date: date | "YYYY-MM-DD"
    is_draft_rookie: bool
    is_two_way: bool
    outgoing_trade_salary: number
    incoming_trade_salary: number
    apron_salary: number
    has_trade_kicker: bool
    poison_pill: bool
    could_expire_current_season: bool
    reacquire_blocked_until_by_team: {team: date | "YYYY-MM-DD"}

Sign-and-trade event fields (only set these when the CURRENT transaction is a
sign-and-trade; a historical contract_type of "Free Agent Sign-and-Trade" is
not enough):

    being_signed_and_traded: bool
    sat_own_free_agent: bool
    sat_finished_prior_season_on_roster: bool
    sat_contract_years_excluding_option: int
    sat_contract_years_including_option: int
    sat_first_year_fully_guaranteed: bool

TEAM OVERRIDES
--------------
Keys are team names. Recognized fields include:

    existing_tpes: [
        {
            "amount": number,
            "expires": date | "YYYY-MM-DD" | None,
            "hard_caps_first_apron": bool,
        }
    ]
    hard_cap_first_apron: bool
    cash_sent_ytd: number | None
    cash_received_ytd: number | None
    frozen_first_round_years: iterable[int]

OPTIONAL GENERIC TRADE FIELDS
-----------------------------
Each move may additionally contain:

    "cash": number

and/or:

    "picks": (
        {
            "year": 2031,
            "round": 1,
            "asset": "exact workbook asset text",  # optional
            "is_swap": False,
            "is_protected": False,
            "is_conditional": False,
            "possible_conveyance_years": (2031, 2032),  # recommended if protected
        },
    )

Those fields are not generated by the supplied trade_variations.py today, but
support is included so the validator remains useful if the trade generator is
expanded later.
"""

