def iter_cba_legal_trades(
    trades: Iterable[Mapping[str, Any]],
    *,
    workbook_path: str | Path,
    trade_date: date,
    rules: Optional[SeasonRules] = None,
    player_overrides: Optional[Mapping[PlayerKey, Mapping[str, Any]]] = None,
    team_overrides: Optional[Mapping[str, Mapping[str, Any]]] = None,
) -> Iterator[Mapping[str, Any]]:
    """
    Yield only candidates that have no detected violation.

    This consumes the generic trade dictionaries themselves; it does not care
    which wanted_players/tradeable_players arguments originally created them.
    """
    validator = CBAValidator.from_xlsx(
        workbook_path,
        trade_date=trade_date,
        rules=rules,
        player_overrides=player_overrides,
        team_overrides=team_overrides,
    )
    yield from validator.iter_legal_trades(trades)


def filter_cba_legal_trades(
    trades: Iterable[Mapping[str, Any]],
    *,
    workbook_path: str | Path,
    trade_date: date,
    rules: Optional[SeasonRules] = None,
    player_overrides: Optional[Mapping[PlayerKey, Mapping[str, Any]]] = None,
    team_overrides: Optional[Mapping[str, Mapping[str, Any]]] = None,
    keep_rejections: bool = False,
    rejection_limit: Optional[int] = None,
) -> Tuple[List[Mapping[str, Any]], List[RejectedTrade]]:
    validator = CBAValidator.from_xlsx(
        workbook_path,
        trade_date=trade_date,
        rules=rules,
        player_overrides=player_overrides,
        team_overrides=team_overrides,
    )
    return validator.filter_trades(
        trades,
        keep_rejections=keep_rejections,
        rejection_limit=rejection_limit,
    )


