def _as_money(value: Any, default: Money = 0.0) -> Money:
    if value in (None, ""):
        return default
    if isinstance(value, bool):
        return float(value)
    if isinstance(value, (int, float)):
        return float(value)
    text = str(value).strip().replace("$", "").replace(",", "")
    if not text:
        return default
    return float(text)


def _as_int(value: Any) -> Optional[int]:
    if value in (None, ""):
        return None
    return int(value)


def _as_bool(value: Any) -> bool:
    if isinstance(value, bool):
        return value
    if value in (None, ""):
        return False
    if isinstance(value, (int, float)):
        return bool(value)
    return str(value).strip().lower() in {"1", "true", "yes", "y"}


def _as_date(value: Any) -> Optional[date]:
    if value in (None, ""):
        return None
    if isinstance(value, datetime):
        return value.date()
    if isinstance(value, date):
        return value
    if isinstance(value, str):
        return date.fromisoformat(value.strip())
    raise TypeError(f"Cannot convert {value!r} to date.")


def _add_months(d: date, months: int) -> date:
    month_index = (d.month - 1) + months
    year = d.year + month_index // 12
    month = month_index % 12 + 1
    day = min(d.day, calendar.monthrange(year, month)[1])
    return date(year, month, day)


def _add_year(d: date) -> date:
    try:
        return d.replace(year=d.year + 1)
    except ValueError:
        # Feb. 29 -> Feb. 28 in a non-leap year.
        return d.replace(month=2, day=28, year=d.year + 1)


def _first_value(row: Mapping[str, Any], *names: str) -> Any:
    for name in names:
        if name in row and row[name] not in (None, ""):
            return row[name]
    return None


def _normalize_header(value: Any) -> str:
    if value is None:
        return ""
    return str(value).strip().lower().replace(" ", "_").replace("/", "_")


def _rows_to_dicts(headers: Sequence[Any], rows: Sequence[Sequence[Any]]) -> List[Dict[str, Any]]:
    keys = [_normalize_header(h) for h in headers]
    output: List[Dict[str, Any]] = []
    for row in rows:
        if not any(value not in (None, "") for value in row):
            continue
        item = {
            key: row[i] if i < len(row) else None
            for i, key in enumerate(keys)
            if key
        }
        output.append(item)
    return output


